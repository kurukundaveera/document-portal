    def invoke(self, user_input: str, chat_history: Optional[List[BaseMessage]] = None) -> str:
        """
        Arguments:
        user_input: The user's question as a string.
        chat_history: Optional list of previous chat messages for context.
        """
        try:
            chat_history = chat_history or []
            payload = {"input": user_input, "chat_history": chat_history}
            answer = self.chain.invoke(payload)
            if not answer:
                self.log.warning(
                    "No answer generated by RAG chain",
                    user_input=user_input,
                    session_id=self.session_id
                )
                return "No answer generated."

            self.log.info(
                "RAG chain invoked successfully",
                user_input=user_input,
                session_id=self.session_id,
                answer_preview=answer[:150],
            )
            return answer

        except Exception as e:
            self.log.error("Error invoking RAG chain", error=str(e))
            raise DocumentPortalException("Failed to invoke RAG chain", sys)

    def _load_llm(self):
        try:
            llm = ModelLoader().load_llm()
            if not llm:
                raise ValueError("LLM could not be loaded")
            self.log.info("LLM loaded successfully", session_id=self.session_id)
            return llm
        except Exception as e:
            self.log.error("Error loading LLM", error=str(e))
            raise DocumentPortalException("Failed to load LLM", sys)
    
    
    @staticmethod
    def _format_docs(docs):
        return "\n\n".join(d.page_content for d in docs)

    def _build_lcel_chain(self):
        try:
            question_rewriter =(
                {"input": itemgetter("input"), "chat_history": itemgetter("chat_history")}
                | self.contextualize_prompt
                | self.llm
                | StrOutputParser()
            )
            retrieve_docs = question_rewriter | self.retriever | self._format_docs
            self.chain = (
                {
                    "context": retrieve_docs,
                    "input": itemgetter("input"),
                    "chat_history": itemgetter("chat_history")
                }
                |self.qa_prompt
                |self.llm
                |StrOutputParser()
            )    
            self.log.info("LCE chain built successfully", session_id=self.session_id)
        except Exception as e:
            self.log.error("Error building LCE chain", error=str(e), session_id=self.session_id)
            raise DocumentPortalException("Failed to build LCE chain", sys)
        
    
